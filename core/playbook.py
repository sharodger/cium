# 排序：实质模块在前，证据 E 靠后（避免"要留证据"压过用户真正的问题）。
_ORDER = {"A": 0, "B": 1, "C": 2, "D": 3, "F": 4, "E": 5, "综合": 9}


def pick(text: str, codes: list[str], max_modules: int = 3) -> tuple[list[str], list[Playbook]]:
    """
    在路由结果基础上补漏、重排，返回模块代号与对应要点。
    排序按关键词命中数（和 router 的打分逻辑一致），同分用 _ORDER 兜底；
    这样"拆除/迁移"这类更具体的问题不会输给泛泛的"业委会"。
    """
    picked = [c for c in codes if c in PLAYBOOKS]
    scores = {c: 1 for c in picked}  # 路由已命中，记 1 分

    for code, words in EXTRA_KEYWORDS.items():
        if code == "综合":
            continue
        hit = sum(1 for w in words if w in text)
        if hit:
            scores[code] = scores.get(code, 0) + hit
            if code not in picked:
                picked.append(code)

    if not picked:
        return ["综合"], [PLAYBOOKS["综合"]]

    picked.sort(key=lambda c: (-scores.get(c, 0), _ORDER.get(c, 9)))
    picked = picked[:max_modules]
    return picked, [PLAYBOOKS[c] for c in picked]
